# Entrada
nome = input("Digite um nome: ")

# Processamento
nome_maiusculo = nome.upper()
nome_minusculo = nome.lower()

# Saída
print(f"Maiúsculo: {nome_maiusculo}")
print(f"Minúsculo: {nome_minusculo}")